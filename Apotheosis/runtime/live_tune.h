#pragma once

// ══════════════════════════════════════════════════════════════════════════════
//  调参通道 (2026-09-13 新增) —— 让【外部脚本】在程序运行中改瞄准参数
// ══════════════════════════════════════════════════════════════════════════════
//
// 为什么需要它
// ------------
// 调 PID 靠"改一次、打一局、看日志"太慢: 一局几分钟, 一轮扫 5 个值就是半小时,
// 而且手感记忆在两次重启之间会失真。真正有效的做法是【连续扫参】: 程序一直开着,
// 脚本每几秒换一组值, 对比同一段录像/同一段实时数据下的抖动指标。
//
// 为什么不是"我自己实现一套热加载"
// --------------------------------
// 程序里【已经有】一条完全正确的重载路径 (ConfigProfiles::load 里那句
// `config.loadConfig(path)` + `runtime_config::publish()`)。自己再写一套解析/发布
// 就会有两份真相, 迟早不一致。
//
// 所以这里【只做触发器】: 监听一个文件, 变了就把它的内容当作配置读进来,
// 再走一次和 Qt 界面完全相同的重载。没有任何新的配置语义。
//
// 安全设计 (按重要性排序)
// ----------------------
//  1. 【默认关闭】。必须存在哨兵文件才启用, 没有就当这个模块不存在。
//  2. 【只接受已存在的完整配置文件】。解析失败什么都不做, 保留上一次好配置 ——
//     绝不会把半截文件(比如正在被写入的)读进来。
//  3. 【只在主线程(Qt 定时器)上跑】。publish() 会拿 configMutex, 而鼠标线程每拍
//     也在读快照 —— 放到主线程定时器上就自动串行化了, 不需要新锁。
//  4. 【所有重活都在"文件真的变了"之后才做】。平时每 poll_ms 只做一次
//     GetFileAttributesEx, 纳秒级。
//
// 协议 (给外部脚本用)
// -------------------
//   <配置目录>\live_tune.enable     ← 哨兵: 存在才启用通道。内容忽略。
//   <配置目录>\live_tune.ini        ← 参数文件: 一个【完整的】配置文件副本。
//                                     脚本写完(先写 .tmp 再改名)这里, 就被应用。
//   <配置目录>\live_tune_ack.txt    ← 回执: 程序每次应用后写一行, 脚本读它确认。
//
// 为什么要 ack: 脚本改完文件不能假定程序已经吃进去了(可能解析失败)。
// 回执里带序号和时间戳, 脚本可以等它推进再采数据, 避免"数据其实还是旧参数"。

namespace live_tune
{
// 启动轮询。poll_ms <= 0 时用默认值 (200ms)。
// 【必须在 QApplication 构造之后、主线程里调用】(内部会建 QTimer)。
void start(int poll_ms = 200);

// 停止轮询(退出时调用; 不调用也不会崩, QTimer 随 app 结束)。
void stop();

// 通道当前是否启用(哨兵文件存在且已成功应用过至少一次)。
bool active();

// ★【同步】检查并应用一次 live_tune.ini(2026-09-15 新增)。
//
//   与定时器执行的 poll() 是同一段代码, 但【立即执行、不等下一拍】。
//   为什么要它: 自动调参的写回验证(write_and_verify)在 UI 线程上阻塞等待
//   快照变化, 而快照只有 QTimer 触发的 poll() 才会更新 —— 那个定时器
//   【同样跑在被阻塞的 UI 线程事件循环上】, 等待期间一次都不会触发,
//   于是"写出去 -> 2 秒内必然验不到 -> 判失败"每轮必现(实机日志: 每轮
//   都报"参数未能真正生效", 而 ack 里的 applied 是等待放弃之后才写出的)。
//   写完文件后直接调这个函数, 就不再依赖事件循环有没有空。
//
//   线程约束与 poll() 相同: 必须在主线程调(publish/syncFromRuntime 的
//   线程纪律不变)。定时器仍在, 它只作为外部脚本路径的兜底。
void poll_now();
}
